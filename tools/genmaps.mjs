/* ============================================================================
 * genmaps.mjs — level map driver: builds the three maps from tools/design-*.mjs
 *
 *   node tools/genmaps.mjs            # check + pretty-print every level
 *   node tools/genmaps.mjs --write    # also emit js/10-levels.js
 *
 * A level is only written out after every design rule check passes, so the
 * maps that ship in js/10-levels.js are exactly the maps validated here.
 * ==========================================================================*/
'use strict';
import { checkDesign, drawMap, summarize, renderRows } from './genmaps-lib.mjs';
import { build as build11 } from './design-11.mjs';
import { build as build12 } from './design-12.mjs';
import { build as build13 } from './design-13.mjs';
import { build as build14 } from './design-14.mjs';
import { build as build15 } from './design-15.mjs';
import { build as build16 } from './design-16.mjs';
import { build as build17 } from './design-17.mjs';
import { build as build18 } from './design-18.mjs';
import { build as build19 } from './design-19.mjs';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const levels = [build11(), build12(), build13(), build14(), build15(), build16(), build17(), build18(), build19()];

let failed = 0;
for (const lv of levels) {
  checkDesign(lv);
  console.log('=== ' + lv.name + ' ' + lv.title + ' ===');
  console.log(summarize(lv));
  console.log(drawMap(lv));
  if (lv.notes.length) {
    console.log('  notes:');
    for (const n of lv.notes) console.log('   ~ ' + n);
  }
  if (lv.errors.length) {
    failed++;
    console.log('  DESIGN ERRORS (' + lv.errors.length + '):');
    for (const e of lv.errors) console.log('   ! ' + e);
  } else {
    console.log('  design rules OK');
  }
}
if (failed) {
  console.log('FAILED: ' + failed + ' level(s) violate the design rules');
  process.exit(1);
}

if (process.argv.indexOf('--write') < 0) {
  console.log('all maps check out; rerun with --write to emit js/10-levels.js');
} else {
  const out = [];
  out.push('/* ============================================================================');
  out.push(' * 10-levels.js — the nine level maps for SUPER GUMDROP BROS.');
  out.push(' * GENERATED by tools/genmaps.mjs from tools/design-11..design-19.mjs');
  out.push(' * (see docs/plan/09-level-design.md).  Do not hand-edit:');
  out.push(' * run  node tools/genmaps.mjs --write  to regenerate.');
  out.push(' * Legend lives in js/09-tiles.js: . empty  G ground  B brick  X hard candy');
  out.push(' * C trampoline  s spikes  p pipe  ?JERO Q-blocks  o bonbon  g q h f r enemy');
  out.push(' * seeds  I flagpole  K Gingerbread Keep.');
  out.push(' * ==========================================================================*/');
  out.push('(function () {');
  out.push("  'use strict';");
  out.push('  const BROS = window.BROS;');
  out.push('  BROS.LEVELS = [');
  for (let i = 0; i < levels.length; i++) {
    const lv = levels[i];
    out.push('    {');
    out.push("      name: '" + lv.name + "',");
    out.push("      title: '" + lv.title + "',");
    out.push("      theme: '" + lv.theme + "',");
    out.push('      time: ' + lv.time + ',');
    out.push('      startCol: ' + lv.startCol + ',');
    const rows = renderRows(lv);
    out.push('      map: [');
    for (let r = 0; r < rows.length; r++) {
      out.push("        '" + rows[r] + "'" + (r < rows.length - 1 ? ',' : ''));
    }
    out.push('      ]');
    out.push('    }' + (i < levels.length - 1 ? ',' : ''));
  }
  out.push('  ];');
  out.push('})();');
  const target = path.join(import.meta.dirname, '..', 'js', '10-levels.js');
  writeFileSync(target, out.join('\n') + '\n');
  console.log('wrote js/10-levels.js (' + levels.length + ' levels)');
}
